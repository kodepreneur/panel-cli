// ApplyVhost generates, validates, and activates an Nginx virtual host configuration
func (m *Manager) ApplyVhost(cfg protocol.VhostConfig) (*protocol.VhostResult, error) {
	if cfg.Slug == "" || cfg.PrimaryDomain == "" {
		return nil, fmt.Errorf("slug and primary_domain are required")
	}

	tmpl, err := template.New("vhost").Parse(vhostTemplate)
	if err != nil {
		return nil, fmt.Errorf("failed to parse template: %w", err)
	}

	var buf bytes.Buffer
	if err := tmpl.Execute(&buf, cfg); err != nil {
		return nil, fmt.Errorf("failed to render vhost template: %w", err)
	}

	if err := os.MkdirAll(m.sitesAvailableDir, 0755); err != nil {
		return nil, fmt.Errorf("failed to create sites-available dir: %w", err)
	}
	if err := os.MkdirAll(m.sitesEnabledDir, 0755); err != nil {
		return nil, fmt.Errorf("failed to create sites-enabled dir: %w", err)
	}

	availableFile := filepath.Join(m.sitesAvailableDir, fmt.Sprintf("%s.conf", cfg.Slug))
	enabledFile := filepath.Join(m.sitesEnabledDir, fmt.Sprintf("%s.conf", cfg.Slug))

	// Write candidate configuration
	if err := os.WriteFile(availableFile, buf.Bytes(), 0644); err != nil {
		return nil, fmt.Errorf("failed to write vhost config: %w", err)
	}

	// Symlink to sites-enabled
	_ = os.Remove(enabledFile)
	if err := os.Symlink(availableFile, enabledFile); err != nil {
		return nil, fmt.Errorf("failed to symlink vhost config: %w", err)
	}

	res := &protocol.VhostResult{
		Success:     true,
		ConfigPath:  availableFile,
		SyntaxValid: true,
	}

	// Test configuration syntax with nginx -t
	if !m.mockMode && m.nginxBinary != "" {
		testCmd := exec.Command(m.nginxBinary, "-t")
		out, err := testCmd.CombinedOutput()
		if err != nil {
			// Syntax failed - rollback symlink to prevent breaking running nginx
			_ = os.Remove(enabledFile)
			res.Success = false
			res.SyntaxValid = false
			res.Error = fmt.Sprintf("nginx syntax test failed: %s (%v)", string(out), err)
			return res, nil
		}

		// Reload Nginx safely
		reloadCmd := exec.Command("systemctl", "reload", "nginx")
		relOut, relErr := reloadCmd.CombinedOutput()
		if relErr != nil {
			res.ReloadOutput = string(relOut)
			res.Error = fmt.Sprintf("systemctl reload nginx failed: %s (%v)", string(relOut), relErr)
		} else {
			res.ReloadOutput = "nginx successfully reloaded"
		}
	} else {
		res.ReloadOutput = "mock mode: config written and symlinked successfully"
	}

	return res, nil
}

// RemoveVhost removes the virtual host configuration and unlinks it
func (m *Manager) RemoveVhost(slug string) error {
	enabledFile := filepath.Join(m.sitesEnabledDir, fmt.Sprintf("%s.conf", slug))
	availableFile := filepath.Join(m.sitesAvailableDir, fmt.Sprintf("%s.conf", slug))

	_ = os.Remove(enabledFile)
	_ = os.Remove(availableFile)

	if !m.mockMode && m.nginxBinary != "" {
		_ = exec.Command("systemctl", "reload", "nginx").Run()
	}
	return nil
}

